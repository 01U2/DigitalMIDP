namespace DigitalMIDP.Infrastructure.Authentication;

/// <summary>
/// Helper class for PKCE (Proof Key for Public Clients Exchange) operations.
/// Used in OAuth 2.0 3-legged flow for desktop applications.
/// </summary>
internal static class PkceHelper
{
    /// <summary>
    /// Generates a random code verifier for PKCE.
    /// </summary>
    /// <returns>A random 128-character base64url-encoded string.</returns>
    public static string GenerateCodeVerifier()
    {
        var randomBytes = new byte[96];
        using (var rng = System.Security.Cryptography.RandomNumberGenerator.Create())
        {
            rng.GetBytes(randomBytes);
        }
        return Base64UrlEncode(randomBytes);
    }

    /// <summary>
    /// Generates a code challenge from a code verifier using SHA256.
    /// </summary>
    /// <param name="codeVerifier">The code verifier generated by GenerateCodeVerifier().</param>
    /// <returns>A base64url-encoded SHA256 hash of the code verifier.</returns>
    public static string GenerateCodeChallenge(string codeVerifier)
    {
        ArgumentException.ThrowIfNullOrWhiteSpace(codeVerifier);

        using (var sha256 = System.Security.Cryptography.SHA256.Create())
        {
            var hash = sha256.ComputeHash(System.Text.Encoding.UTF8.GetBytes(codeVerifier));
            return Base64UrlEncode(hash);
        }
    }

    /// <summary>
    /// Encodes bytes to a base64url string (RFC 4648 section 5).
    /// </summary>
    private static string Base64UrlEncode(byte[] input)
    {
        var output = Convert.ToBase64String(input);
        return output
            .Replace('+', '-')
            .Replace('/', '_')
            .TrimEnd('=');
    }
}
